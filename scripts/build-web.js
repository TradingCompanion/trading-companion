// The VRM carries a 2.5 MB preview thumbnail that nothing on a web page ever shows; the copy the
// browser downloads goes without it (a GLB rewrite: same JSON, the BIN chunk re-packed minus that
// image's bytes, every later bufferView re-offset). A gzip twin sits beside it for the server to
// hand out as Content-Encoding: gzip — the mesh and skin data compress, the PNGs do not, but the
// download still comes out a fifth smaller.
const zlib = require('zlib');
function stripThumbnail(buf) {
  const jsonLen = buf.readUInt32LE(12);
  const json = JSON.parse(buf.slice(20, 20 + jsonLen).toString('utf8'));
  const binStart = 20 + jsonLen + 8;
  const bin = buf.slice(binStart, binStart + buf.readUInt32LE(20 + jsonLen));
  const meta0 = json.extensions && json.extensions.VRM && json.extensions.VRM.meta;
  const meta1 = json.extensions && json.extensions.VRMC_vrm && json.extensions.VRMC_vrm.meta;
  const thumbTex = meta0 && typeof meta0.texture === 'number' ? meta0.texture : null;
  const thumbImg = meta1 && typeof meta1.thumbnailImage === 'number' ? meta1.thumbnailImage
    : thumbTex != null && json.textures[thumbTex] ? json.textures[thumbTex].source : null;
  const byName = (json.images || []).findIndex((im) => /thumbnail/i.test(im.name || ''));
  const img = thumbImg != null ? thumbImg : byName;
  if (img < 0 || !json.images[img] || json.images[img].bufferView == null) return { buf, saved: 0 };
  // is that image used by any material? then it is not just a preview and stays
  const src = json.images[img];
  const usedBy = (json.textures || []).map((t, i) => (t.source === img ? i : -1)).filter((i) => i >= 0);
  const inMaterial = JSON.stringify(json.materials || []).match(/"index":(\d+)/g) || [];
  if (usedBy.some((ti) => inMaterial.includes('"index":' + ti))) return { buf, saved: 0 };
  const dropBv = src.bufferView;
  // re-pack the BIN without that view
  const views = json.bufferViews;
  const parts = []; let offset = 0;
  const newIndex = new Map();
  views.forEach((bv, i) => {
    if (i === dropBv) return;
    const data = bin.slice(bv.byteOffset || 0, (bv.byteOffset || 0) + bv.byteLength);
    const pad = (4 - (offset % 4)) % 4; if (pad) { parts.push(Buffer.alloc(pad)); offset += pad; }
    newIndex.set(i, { ...bv, byteOffset: offset });
    parts.push(data); offset += data.length;
  });
  const newViews = []; const remap = new Map();
  views.forEach((bv, i) => { if (i !== dropBv) { remap.set(i, newViews.length); newViews.push(newIndex.get(i)); } });
  const fix = (o) => { if (o && typeof o.bufferView === 'number') o.bufferView = remap.get(o.bufferView); };
  (json.accessors || []).forEach((a) => { fix(a); if (a.sparse) { fix(a.sparse.indices); fix(a.sparse.values); } });
  (json.images || []).forEach(fix);
  json.bufferViews = newViews;
  json.buffers[0].byteLength = offset;
  // the image itself: keep the slot (indices elsewhere stay valid) but point it at nothing
  json.images[img] = { name: src.name, mimeType: src.mimeType, uri: 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNkYAAAAAYAAjCB0C8AAAAASUVORK5CYII=' };
  const newBin = Buffer.concat(parts);
  let jsonBuf = Buffer.from(JSON.stringify(json), 'utf8');
  const jpad = (4 - (jsonBuf.length % 4)) % 4; if (jpad) jsonBuf = Buffer.concat([jsonBuf, Buffer.alloc(jpad, 0x20)]);
  const header = Buffer.alloc(12); header.writeUInt32LE(0x46546C67, 0); header.writeUInt32LE(2, 4);
  const jh = Buffer.alloc(8); jh.writeUInt32LE(jsonBuf.length, 0); jh.writeUInt32LE(0x4E4F534A, 4);
  const bh = Buffer.alloc(8); bh.writeUInt32LE(newBin.length, 0); bh.writeUInt32LE(0x004E4942, 4);
  const out = Buffer.concat([header, jh, jsonBuf, bh, newBin]);
  out.writeUInt32LE(out.length, 8);
  return { buf: out, saved: buf.length - out.length };
}
const vrm = path.join(ROOT, 'models', 'shino.vrm');
const out = path.join(WEB, 'assets', 'yui.vrm');
// rebuilt when the model changes *or* when this script does — the stripping happens here, so a
