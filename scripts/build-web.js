// ---- motion clips ------------------------------------------------------------------------------
// Converted humanoid clips (tools/clips/convert.mjs → clips/**.json, a symlink to the converted
// pack). Big JSON, so a gzip twin sits beside each for the server, like her body; only rebuilt
// when the clip is newer.
{
  const src = path.join(ROOT, 'clips'), dst = path.join(WEB, 'assets', 'clips');
  let n = 0, gz = 0;
  (function walk(rel) {
    const from = path.join(src, rel);
    if (!fs.existsSync(from)) return;
    for (const f of fs.readdirSync(from)) {
      const r = path.join(rel, f);
      if (fs.statSync(path.join(src, r)).isDirectory()) { walk(r); continue; }
      if (!/\.json$/.test(f)) continue;
      const a = path.join(src, r), b = path.join(dst, r);
      fs.mkdirSync(path.dirname(b), { recursive: true });
      const st = fs.statSync(a);
      if (!fs.existsSync(b) || fs.statSync(b).mtimeMs < st.mtimeMs) { fs.copyFileSync(a, b); fs.writeFileSync(b + '.gz', zlib.gzipSync(fs.readFileSync(a), { level: 6 })); gz++; }
      n++;
    }
  })('');
  console.log('[web] ' + n + ' motion clips in place (' + gz + ' rewritten)');
}

