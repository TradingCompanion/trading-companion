const vrmStamp = Math.max(fs.statSync(vrm).mtimeMs, fs.statSync(__filename).mtimeMs);
if (!fs.existsSync(out + '.gz') || vrmStamp > fs.statSync(out + '.gz').mtimeMs) {
  const { buf, saved } = stripThumbnail(fs.readFileSync(vrm));
  fs.writeFileSync(out, buf);
  fs.writeFileSync(out + '.gz', zlib.gzipSync(buf, { level: 9 }));
  console.log('[web] assets/yui.vrm written (' + (buf.length / 1048576).toFixed(1) + ' MB, thumbnail ' + (saved ? 'stripped: −' + (saved / 1048576).toFixed(1) + ' MB' : 'kept') + '; gzip ' + (fs.statSync(out + '.gz').size / 1048576).toFixed(1) + ' MB)');
}

