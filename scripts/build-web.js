  // makes her canvas catch the mouse whenever the cursor is over the panel or the tour card (that
  // is how the app window stops being click-through there), and her canvas is 2.2x her height:
  // left below the card in z-order it would sit on top of the card's inputs and take every click
  // meant for them — as a grab. Same order as the app (tour above panel above bubble), lifted.
