// Builds the Chrome extension: Yui on a trading site, out of the same renderer the app and the
// website run. Output is extension/dist/ — load it unpacked from chrome://extensions, or upload
// the zip it leaves in release/ to the Web Store.
//
//   npm run build:ext          # release build + release/yui-extension-<version>.zip
//   npm run build:ext -- --dev # also matches http://127.0.0.1 and localhost, and keeps the
//                              # self-test's way in (scripts/test-extension.js uses this)
//
// The web build is run first: it produces her stylesheet, defaults and voice list from the app's
// own sources, and this script only adapts them to a shadow root on someone else's page.
'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'extension', 'src');
const OUT = path.join(ROOT, 'extension', 'dist');
const WEB = path.join(ROOT, 'web');
const DEV = process.argv.includes('--dev') || process.env.YUI_EXT_DEV === '1';
const WIN = process.platform === 'win32';
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));

// ---- where she appears -------------------------------------------------------------------------
// Match patterns, one line per terminal. Adding a site is adding a line here; the same list is
// the content-script matches, the host permissions and the resource allow-list.
const SITES = [
  'https://axiom.trade/*', 'https://*.axiom.trade/*',
  'https://pump.fun/*', 'https://*.pump.fun/*',
  'https://bullx.io/*', 'https://*.bullx.io/*',
  'https://photon-sol.tinyastro.io/*',
  'https://gmgn.ai/*',
  'https://trade.padre.gg/*',
];
const DEV_SITES = ['http://127.0.0.1/*', 'http://localhost/*'];
const MATCHES = DEV ? SITES.concat(DEV_SITES) : SITES;

// ---- the web build first -------------------------------------------------------------------------
execFileSync(process.execPath, [path.join(ROOT, 'scripts', 'build-web.js')], { cwd: ROOT, stdio: 'inherit' });

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
const write = (rel, data) => { const f = path.join(OUT, rel); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, data); };
const copy = (from, rel) => { const f = path.join(OUT, rel); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.copyFileSync(from, f); };

// ---- her stylesheet, for a shadow root -----------------------------------------------------------
// pet.css is the app's stylesheet as the website uses it. In a shadow root two things differ: there
// is no <body> (the renderer's canvases land in #yui-body), and a rule on <html> cannot live inside
// the root (content.js puts the grabbing rule in the page's head instead).
let css = fs.readFileSync(path.join(WEB, 'pet.css'), 'utf8');
if (!css.includes('body > canvas')) throw new Error('pet.css changed shape: no "body > canvas" rule to adapt');
css = css.split('body > canvas').join('#yui-body > canvas');
css = css.replace(/\n[^\n]*html\.yui-grabbing[^\n]*\n/, '\n');
write('yui.css', '/* Generated by scripts/build-extension.js from web/pet.css — do not edit by hand. */\n' + `
/* Her host: the whole viewport, on top of everything, transparent to the pointer. Only her canvas
   (when she is under the cursor), her panel, her bubble and the tour card ever catch a click. */
:host { all: initial; position: fixed; inset: 0; z-index: 2147483647; pointer-events: none; display: block;
        font: 14px system-ui, sans-serif; color: #fff; }
#yui-body { display: contents; }
#panel, #tour { pointer-events: auto; }
` + css);

// ---- her defaults and her voice --------------------------------------------------------------------
copy(path.join(WEB, 'yui-defaults.js'), 'yui-defaults.js');
copy(path.join(WEB, 'yui-sounds.js'), 'yui-sounds.js');     // URLs are relative; content.js resolves them

// ---- the bundles -------------------------------------------------------------------------------------
const esbuildBin = path.join(ROOT, 'node_modules', 'esbuild', 'bin', 'esbuild');
function esbuild(args) {
  if (WIN) execFileSync(process.execPath, [esbuildBin, ...args], { cwd: ROOT, stdio: 'inherit' });
  else execFileSync(esbuildBin, args, { cwd: ROOT, stdio: 'inherit' });
}
// YUI_EXT_DEBUG=1 leaves the bundles readable, for a stack trace that names a line.
const common = ['--bundle', '--format=iife', ...(process.env.YUI_EXT_DEBUG ? [] : ['--minify']), '--target=chrome116', '--log-level=warning'];
// The renderer and the website's bridge, unchanged, with three globals redirected (see content.js).
esbuild(['extension/src/bundle-entry.js', '--outfile=' + path.join(OUT, 'yui-bundle.js'), ...common,
  '--define:document=__YUI_DOC', '--define:WebSocket=__YUI_WS', '--define:requestAnimationFrame=__YUI_RAF']);
esbuild(['extension/src/content.js', '--outfile=' + path.join(OUT, 'yui-content.js'), ...common, '--define:YUI_DEV=' + (DEV ? 'true' : 'false')]);
esbuild(['extension/src/background.js', '--outfile=' + path.join(OUT, 'background.js'), ...common]);
esbuild(['extension/src/popup.js', '--outfile=' + path.join(OUT, 'popup.js'), ...common]);
copy(path.join(SRC, 'popup.html'), 'popup.html');

// ---- her body, her voice, her fonts, her icon ------------------------------------------------------
copy(path.join(WEB, 'assets', 'yui.vrm'), 'assets/yui.vrm');
for (const f of fs.readdirSync(path.join(WEB, 'assets', 'sounds'))) copy(path.join(WEB, 'assets', 'sounds', f), 'assets/sounds/' + f);
for (const f of ['Rubik.woff2', 'Outfit.woff2']) copy(path.join(ROOT, 'fonts', f), 'fonts/' + f);
for (const n of [16, 32, 48, 128]) copy(path.join(ROOT, 'extension', 'icons', 'icon' + n + '.png'), 'icons/icon' + n + '.png');

// ---- the manifest --------------------------------------------------------------------------------------
const manifest = {
  manifest_version: 3,
  name: 'Yui — Trading Companion',
  short_name: 'Yui',
  version: pkg.version,
  // the store caps this at 132 characters
  description: 'An anime companion on your trading terminal who reacts to your trades: cheers wins, feels losses, holds your live PnL.',
  minimum_chrome_version: '116',
  icons: { 16: 'icons/icon16.png', 32: 'icons/icon32.png', 48: 'icons/icon48.png', 128: 'icons/icon128.png' },
  action: { default_title: 'Yui', default_popup: 'popup.html', default_icon: { 16: 'icons/icon16.png', 32: 'icons/icon32.png' } },
  permissions: ['storage'],
  host_permissions: MATCHES,
  background: { service_worker: 'background.js' },
  content_scripts: [{
    matches: MATCHES,
    js: ['yui-defaults.js', 'yui-sounds.js', 'yui-bundle.js', 'yui-content.js'],
    run_at: 'document_idle',
    all_frames: false,
  }],
  web_accessible_resources: [{ resources: ['yui.css', 'assets/*', 'fonts/*'], matches: MATCHES }],
};
write('manifest.json', JSON.stringify(manifest, null, 2) + '\n');

// ---- nothing private ships ---------------------------------------------------------------------------
// The same rules the desktop package is checked with. The sources that go into the bundles get every
// rule; the minified bundles themselves get all but the wallet-shape one, which a long minified line
// of three.js identifiers trips by shape alone (the sources it came from were checked in full).
// The public relay is allowed by name (scripts/package-allow.txt); a token or a wallet is not.
const RULES = [
  [/\b(?!127\.0\.0\.1\b|0\.0\.0\.0\b|255\.255\.255\.255\b)(?:\d{1,3}\.){3}\d{1,3}\b/, 'a bare IP address'],
  [/\bwss?:\/\/(?!localhost\b|127\.0\.0\.1\b)[A-Za-z0-9][A-Za-z0-9.-]{2,}(?::\d+)?/i, 'a hard-coded relay URL'],
  [/\b(?=(?:[^0-9\s]*[0-9]){2})[1-9A-HJ-NP-Za-km-z]{32,44}\b/, 'something shaped like a Solana address or token', 'sources-only'],
  [/\b(?:api[-_]?key|secret|password|private[-_]?key|relaytoken)\b\s*[:=]\s*["'][^"']{8,}/i, 'a credential'],
];
const ALLOW = fs.readFileSync(path.join(ROOT, 'scripts', 'package-allow.txt'), 'utf8').split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('#'));
const hits = [];
function scanFile(p, minified) {
  fs.readFileSync(p, 'utf8').split('\n').forEach((line, i) => {
    for (const [re, what, only] of RULES) {
      if (minified && only === 'sources-only') continue;
      const m = line.match(re);
      if (m && !ALLOW.includes(m[0])) hits.push(path.relative(ROOT, p) + ':' + (i + 1) + '  ' + what + '  ->  ' + m[0].slice(0, 48));
    }
  });
}
const SOURCES = ['src/renderer.js', 'src/voice.js', 'src/voice-lines.js', 'web/yui-boot.js',
  ...fs.readdirSync(SRC).map((f) => 'extension/src/' + f)];
for (const rel of SOURCES) scanFile(path.join(ROOT, rel), false);
(function walk(dir) {
  for (const f of fs.readdirSync(dir)) {
    const p = path.join(dir, f);
    if (fs.statSync(p).isDirectory()) { walk(p); continue; }
    if (/\.(js|json|html|css)$/.test(f)) scanFile(p, /^(yui-bundle|yui-content|background|popup)\.js$/.test(f));
  }
})(OUT);
if (hits.length) { console.error('[ext] REFUSING TO BUILD — these would ship inside the extension:\n  ' + hits.join('\n  ')); process.exit(1); }
console.log('[ext] clean: no addresses, tokens or wallets in anything that ships (' + SOURCES.length + ' sources + dist)');

// ---- the zip for the store -------------------------------------------------------------------------------
const total = (function sum(dir) { let n = 0; for (const f of fs.readdirSync(dir)) { const p = path.join(dir, f); n += fs.statSync(p).isDirectory() ? sum(p) : fs.statSync(p).size; } return n; })(OUT);
console.log('[ext] extension/dist ready — ' + (total / 1048576).toFixed(1) + ' MB, ' + MATCHES.length + ' site patterns' + (DEV ? ' (dev build: localhost included, test bridge in)' : ''));
if (!DEV) {
  const rel = path.join(ROOT, 'release');
  fs.mkdirSync(rel, { recursive: true });
  const zip = path.join(rel, 'yui-extension-' + pkg.version + '.zip');
  fs.rmSync(zip, { force: true });
  try {
    execFileSync('zip', ['-qr', zip, '.'], { cwd: OUT, stdio: 'inherit' });
    console.log('[ext] ' + path.relative(ROOT, zip) + ' (' + (fs.statSync(zip).size / 1048576).toFixed(1) + ' MB) — upload this to the Web Store');
  } catch (e) {
    console.log('[ext] no `zip` on this machine; zip the contents of extension/dist yourself (' + e.message + ')');
  }
}
